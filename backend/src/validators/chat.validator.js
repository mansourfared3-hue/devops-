// التحقّق من بيانات الشات.
// كل دالة بتاخد body وترجّع رسالة خطأ (نص) أو null لو كله تمام.
// بنستخدم if بسيطة بدل مكتبة (زي Zod) عشان الكود يفضل مقروء لأي حد.
//
// ملحوظة: جلب الرسائل بياخد الغرفة من الرابط (?room=sec-1) مش من الـbody،
// والـvalidate middleware بيشتغل على الـbody بس — عشان كده التحقّق بتاعه في الـservice.

// إرسال رسالة جديدة
function sendMessage(body) {
  const { room, text } = body;

  // الاتنين بيتشيّكوا مع بعض ورسالة واحدة — زي ما كان الكود القديم بالظبط
  if (!room || !text) return 'الغرفة والرسالة مطلوبين';

  return null; // كله تمام
}

module.exports = { sendMessage };
