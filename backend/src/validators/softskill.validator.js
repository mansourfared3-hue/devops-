// التحقّق من بيانات السوفت سكيلز.
// كل دالة بتاخد body وترجّع رسالة خطأ (نص) أو null لو كله تمام.
// بنستخدم if بسيطة بدل مكتبة (زي Zod) عشان الكود يفضل مقروء لأي حد.

// إنشاء تاسك جديد
function createTask(body) {
  const { title } = body;

  if (!title) return 'العنوان مطلوب';

  return null; // كله تمام
}

// ملاحظة: تسليم الطالب مالوش validator هنا،
// لأن اللي بيتبعت ملف مش body — والتأكد من الملف بيحصل في الـservice.
//
// وكمان التصحيح (grade / feedback) مالوش validator،
// لأن المعلم ممكن يبعت الدرجة لوحدها أو الملاحظة لوحدها — الاتنين اختياريين.

module.exports = { createTask };
